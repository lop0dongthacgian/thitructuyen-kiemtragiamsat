function initTheLeModal() {
if (document.getElementById('theLeModal')) return;
const modalHTML = `
    <div id="theLeModal" class="modal-word">
        <div class="modal-content-word">
            <span class="close-word" onclick="closeTheLeModal()">&times;</span>
            <div class="word-doc" id="theLeContent"></div>
        </div>
    </div>
`;
document.body.insertAdjacentHTML('beforeend', modalHTML);
document.getElementById('theLeContent').innerHTML = getTheLeHTML();
}
// Hàm mở modal
function openTheLeModal() {
initTheLeModal();
document.getElementById('theLeModal').style.display = "block";
document.body.style.overflow = "hidden";
}
// Hàm đóng modal
function closeTheLeLeModal() {
const modal = document.getElementById('theLeModal');
if (modal) {
modal.style.display = "none";
document.body.style.overflow = "auto";
}
}
// Click ra ngoài để đóng
window.addEventListener('click', function(event) {
const modal = document.getElementById('theLeModal');
if (event.target === modal) {
closeTheLeModal();
}
});
